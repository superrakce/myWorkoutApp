test('required calculation inputs prevent incomplete records and profile saves', async ({ page }) => {
  await openBody(page)
  const age = page.getByLabel('Age on measurement date', { exact: true })
  const sex = page.getByRole('combobox', { name: 'Formula sex parameter', exact: true })
  const height = page.getByLabel('Height (cm)', { exact: true })
  const weight = page.getByLabel('Body weight (kg)', { exact: true })
  const date = page.getByLabel('Measurement date and time', { exact: true })
  for (const field of [age, sex, height, weight, date])
    await expect(field).toHaveAttribute('required', '')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.history-row')).toHaveCount(0)
  await expect(page.getByRole('status')).toHaveCount(0)
  await age.fill('30')
  await page.getByRole('button', { name: 'Save age and formula parameter', exact: true }).click()
  await expect(page.getByRole('status')).toHaveCount(0)
  await sex.selectOption('male')
  await weight.fill('70')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.history-row')).toHaveCount(0)
  await height.fill('175')
  const originalDate = await date.inputValue()
  await date.fill('')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.history-row')).toHaveCount(0)
  await date.fill(originalDate)
  await weight.fill('')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.history-row')).toHaveCount(0)
  await weight.fill('70')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Saved')
  await expect(page.locator('.history-row')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.metric-card').filter({ hasText: 'Estimated resting energy' }).locator('.metric-number')).toContainText('1,649')
})

test('one measurement date anchors age and survives reload and historical editing', async ({ page }) => {
  await openBody(page)
  await expect(page.locator('input[type="date"]')).toHaveCount(0)
  await expect(page.locator('input[type="datetime-local"]')).toHaveCount(1)
  const date = page.getByLabel('Measurement date and time', { exact: true })
  const today = (await date.inputValue()).slice(0, 10)
  const prior = String(Number(today.slice(0, 4)) - 1) + today.slice(4) + 'T12:00'
  await date.fill(prior)
  await page.getByLabel('Age on measurement date', { exact: true }).fill('30')
  await page.getByRole('combobox', { name: 'Formula sex parameter', exact: true }).selectOption('male')
  await page.getByLabel('Height (cm)', { exact: true }).fill('175')
  await page.getByLabel('Body weight (kg)', { exact: true }).fill('70')
  await expect(page.getByTestId('calculated-estimatedRmrField')).toHaveValue('1,649')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Saved')
  await page.reload()
  await expect(page.getByLabel('Age on measurement date', { exact: true })).toHaveValue('31')
  await expect(page.locator('.metric-card').filter({ hasText: 'Estimated resting energy' }).locator('.metric-number')).toContainText('1,644')
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(page.getByLabel('Age on measurement date', { exact: true })).toHaveValue('30')
  await expect(page.getByTestId('calculated-estimatedRmrField')).toHaveValue('1,649')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Saved')
  await expect(page.locator('.history-row')).toHaveCount(1)
})
