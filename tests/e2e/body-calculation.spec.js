import { test, expect } from '@playwright/test'
async function openBody(page) {
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('form-locale', 'en'))
  await page.reload()
  await page.goto('/#/body')
}
test('body results update while typing, remain read-only, and persist after saving', async ({ page }) => {
  await openBody(page)
  const rmr = page.getByTestId('calculated-estimatedRmrField')
  await expect(rmr).toHaveAttribute('readonly', '')
  await expect(page.getByTestId('calculated-bmi')).toHaveAttribute('readonly', '')
  await expect(page.getByTestId('calculated-lean')).toHaveAttribute('readonly', '')
  await page.getByLabel('Height (cm)', { exact: true }).fill('175')
  await page.getByLabel('Body weight (kg)', { exact: true }).fill('70')
  await page.getByLabel('Body fat (%)', { exact: true }).fill('20')
  await expect(page.getByTestId('calculated-bmi')).toHaveValue('22.9')
  await expect(page.getByTestId('calculated-lean')).toHaveValue('56')
  await expect(rmr).toHaveValue('—')
  await expect(page.getByTestId('estimate-help')).toContainText('Age on measurement date')
  await page.getByLabel('Age on measurement date', { exact: true }).fill('30')
  await page.getByRole('combobox', { name: 'Formula sex parameter', exact: true }).selectOption('male')
  await expect(rmr).toHaveValue('1,649')
  await page.getByLabel('Body weight (kg)', { exact: true }).fill('80')
  await expect(rmr).toHaveValue('1,749')
  await page.getByLabel('Body weight (kg)', { exact: true }).fill('70')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Saved')
  await page.reload()
  const card = page.locator('.metric-card').filter({ hasText: 'Estimated resting energy' })
  await expect(card.locator('.metric-number')).toContainText('1,649')
  await page.getByRole('combobox', { name: 'Formula sex parameter', exact: true }).selectOption('female')
  await page.getByRole('button', { name: 'Save age and formula parameter', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Saved')
  await expect(card.locator('.metric-number')).toContainText('1,483')
  await page.reload()
  await expect(card.locator('.metric-number')).toContainText('1,483')
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(page.getByTestId('calculated-estimatedRmrField')).toHaveValue('1,483')
  await expect(page.getByLabel('Measured resting energy (kcal/day)', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: '繁中', exact: true }).click()
  await expect(page.getByText('系統自動計算・唯讀', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
