import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
async function open(page) {
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('form-locale', 'en'))
  await page.reload(); await page.goto('/#/exercises')
}
async function create(page) {
  await page.getByRole('button', { name: 'Add exercise', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Exercise editor', exact: true })
  await dialog.getByLabel('English name', { exact: true }).fill('Orbit row')
  await dialog.getByLabel('Traditional Chinese name', { exact: true }).fill('環繞划船')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog).not.toBeVisible()
}
const card = (page, name) => page.locator('.exercise-card').filter({ hasText: name })
test('custom exercise CRUD, plan playback, snapshot history and backup survive reload', async ({ page }) => {
  await open(page); await create(page)
  await page.reload()
  await expect(card(page, 'Orbit row')).toBeVisible()
  await card(page, 'Orbit row').getByRole('button', { name: 'Edit', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Exercise editor', exact: true })
  await dialog.getByLabel('English name', { exact: true }).fill('Orbit row revised')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await card(page, 'Orbit row revised').getByRole('button', { name: 'Add to plan', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Add', exact: true }).click()
  await page.goto('/#/plans')
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: '1. Orbit row revised', exact: true })).toBeVisible()
  await page.getByLabel('Sets', { exact: true }).fill('1')
  for (const key of ['Preparation', 'Between exercises', 'Between rounds', 'Cooldown'])
    await page.getByLabel(key + ' (Seconds)', { exact: true }).fill('0')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('button', { name: 'Start training', exact: true }).first().click()
  await page.getByRole('button', { name: 'Start training', exact: true }).click()
  await page.getByRole('button', { name: 'Complete this set', exact: true }).click()
  await page.getByRole('button', { name: 'Save session', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Activity', exact: true }).first()).toBeVisible()
  await page.goto('/#/exercises')
  page.once('dialog', dialog => dialog.accept())
  await card(page, 'Orbit row revised').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(card(page, 'Orbit row revised')).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('Exercise deleted')
  await page.reload()
  await expect(card(page, 'Orbit row revised')).toHaveCount(0)
  await page.goto('/#/plans')
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: '1. Orbit row revised', exact: true })).toBeVisible()
  await page.goto('/#/settings')
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export full backup', exact: true }).click()
  const backup = JSON.parse(await readFile(await (await downloaded).path(), 'utf8'))
  expect(backup.data.exerciseLibrary[0].deleted).toBe(true)
  expect(backup.data.sessions[0].logs[0].exercise.name.en).toBe('Orbit row revised')
  await page.locator('input[type=file]').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) })
  const restore = page.getByRole('dialog')
  const current = page.waitForEvent('download')
  await restore.getByRole('button', { name: 'Export full backup', exact: true }).click(); await current
  await restore.getByRole('button', { name: 'Replace local data with this backup', exact: true }).click()
  await expect(restore).not.toBeVisible()
  await page.reload(); await page.goto('/#/plans')
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: '1. Orbit row revised', exact: true })).toBeVisible()
})
test('built-in edits, cancellation, delete cancellation, bilingual editor and mobile layout', async ({ page }) => {
  await open(page)
  const original = card(page, 'Push-up').filter({ has: page.getByRole('button', { name: 'Push-up', exact: true }) }).first()
  await original.getByRole('button', { name: 'Edit', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'Exercise editor', exact: true })
  await expect(dialog).toHaveCSS('background-color', 'rgb(32, 57, 70)')
  await expect(dialog.getByRole('heading', { name: 'Edit exercise', exact: true })).toHaveCSS('color', 'rgb(241, 245, 246)')
  await expect(page.locator('.search-box')).toHaveCSS('background-color', 'rgb(32, 57, 70)')
  await expect(page.locator('.segmented .active')).toHaveCSS('background-color', 'rgb(32, 57, 70)')
  await dialog.getByLabel('English name', { exact: true }).fill('Unsaved change')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(card(page, 'Unsaved change')).toHaveCount(0)
  await original.getByRole('button', { name: 'Edit', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Exercise editor', exact: true })
  await dialog.getByLabel('English name', { exact: true }).fill('Personal push-up')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  page.once('dialog', dialog => dialog.dismiss())
  await card(page, 'Personal push-up').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(card(page, 'Personal push-up')).toBeVisible()
  await page.reload()
  await expect(card(page, 'Personal push-up')).toBeVisible()
  await page.getByRole('button', { name: '繁中', exact: true }).click()
  await page.getByRole('button', { name: '新增動作', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '動作編輯', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
